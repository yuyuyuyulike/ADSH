package com.adsh.app.ui

import androidx.compose.ui.unit.dp

/**
 * 横向/纵向的**间距刻度**。
 *
 * 熵减前的现状：`Arrangement.spacedBy(DshSpacing.Xl)` 这类调用全库有 133 处、散布 20 个文件，
 * 值只有 8 种（8/6/4/10/12/2/16/14），但**没有名字** —— 于是
 *  - 「同一个视觉决定」想统一时得先数一遍 `grep`，改的时候还容易漏；
 *  - 新写的组件只能照抄邻近文件的数字，抄错也没人发现。
 *
 * 这里只做一件事：**把已经存在的刻度命名**。名字刻意不写成 "LabelGap" 这种语义名 ——
 * 实测下来同一个值在图标↔文案、菜单行、按钮组之间来回用，硬起语义名反而会误导；
 * 按刻度命名 + 下面这条对应关系，才是这批数据真正支持的结论。
 *
 * 改动口径：只动名字，不动数值。要调间距就在这里改一处，界面自然跟着变。
 */
object DshSpacing {

    /**
     * 0.5dp：分线 / 细边（dsh 的 hairline）。
     *
     * 第 183 轮把全库 **42 处** `0.5.dp` 字面量一次性换成了这个刻度（border /
     * HorizontalDivider / 描边宽度都有，值完全相同）：细边的厚度从此只有这一个来源。
     * **新写的细边一律用它**；这里也是全库唯一还允许出现 0.5dp 字面量的地方 —— 就是它的定义。
     */
    val Hairline = 0.5.dp

    /** 1dp：贴边的细分隔 */
    val Xxs = 1.dp

    /** 2dp：紧邻元素（答案条目、标签内的行） */
    val Xs = 2.dp

    /** 3dp：紧邻元素（弹层内的小行距） */
    val Sm = 3.dp

    /** 4dp：紧凑相邻元素 */
    val Md = 4.dp

    /** 6dp：图标↔文案、菜单行内元素（dsh 用得像基准刻度） */
    val Lg = 6.dp

    /** 8dp：动作之间、卡片内的常规间距 */
    val Xl = 8.dp

    /** 10dp：卡片内的分行 */
    val Xxl = 10.dp

    /** 12dp：分节之间、按钮与内容之间 */
    val Xxxl = 12.dp

    /** 14dp：大分节之间 */
    val Section = 14.dp

    /** 16dp：卡片内边距级别的间距 */
    val Card = 16.dp

    /** 20dp：页面级留白 */
    val Page = 20.dp
}