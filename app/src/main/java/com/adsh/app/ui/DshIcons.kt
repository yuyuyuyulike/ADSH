object DshIcons {

    private fun vector(
        name: String,
        viewBox: Float,
        paths: List<Triple<String, Boolean, Float>>,
    ): ImageVector {
        val builder = ImageVector.Builder(
            name = name,
            defaultWidth = viewBox.dp,
            defaultHeight = viewBox.dp,
            viewportWidth = viewBox,
            viewportHeight = viewBox,
        )
        paths.forEach { (data, stroked, strokeWidth) ->
            val nodes = PathParser().parsePathString(data).toNodes()
            if (stroked) {
                builder.addPath(
                    pathData = nodes,
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = strokeWidth,
                    strokeLineJoin = StrokeJoin.Round,
                )
            } else {
                builder.addPath(pathData = nodes, fill = SolidColor(Color.Black))
            }
        }
        return builder.build()
    }

    private fun filled(name: String, viewBox: Float, vararg data: String): ImageVector =
        vector(name, viewBox, data.map { Triple(it, false, 0f) })


    /** 带 group 变换的图标（Compose 的 addGroup 是入栈/出栈式，不是 lambda） */
    private fun grouped(
        name: String,
        path: String,
        translationX: Float = 0f,
        translationY: Float = 0f,
        scaleX: Float = 1f,
    ): ImageVector {
        val builder = ImageVector.Builder(
            name = name,
            defaultWidth = 16.dp,
            defaultHeight = 16.dp,
            viewportWidth = 16f,
            viewportHeight = 16f,
        )
        builder.addGroup(
            pivotX = 8f,
            pivotY = 8f,
            scaleX = scaleX,
            translationX = translationX,
            translationY = translationY,
        )
        builder.addPath(PathParser().parsePathString(path).toNodes(), fill = SolidColor(Color.Black))
        builder.clearGroup()
        return builder.build()
    }

