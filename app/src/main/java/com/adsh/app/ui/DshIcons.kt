 * 与 dsh-client-ui-conversation 的 PermissionSelect，用 PathParser 还原成 ImageVector。
 *
 * 不手绘、不用 Material 的近似图标 —— 之前的回形针/盾牌「形态不对」就是因为用了近似图标。
